-- =====================================================================
-- Sofi10 database schema — PostgreSQL 15+ / Supabase
-- Safe to run on a blank database. Contains no personal data.
-- Design notes:
--   * One row per game in `games`; the live round lives in games.state (jsonb)
--     and every move is a single transaction (SELECT ... FOR UPDATE) that bumps
--     games.version. Clients are told "version N changed" and re-fetch their own
--     view, so other players' hands never leave the server.
--   * RLS is enabled with no policies: the browser (anon key) can read nothing.
--     Only the app server, connecting as the database owner, reads/writes.
--   * Passwords: bcrypt via pgcrypto, wrapped in app_* functions so the same
--     SQL works on local Postgres (extension in public) and Supabase (extensions schema).
-- =====================================================================

create extension if not exists pgcrypto;

-- ---------- Password helpers ----------
create or replace function public.app_hash_password(p_plain text)
returns text
language sql
volatile
set search_path = public, extensions
as $$ select crypt(p_plain, gen_salt('bf', 10)) $$;

create or replace function public.app_check_password(p_plain text, p_hash text)
returns boolean
language sql
stable
set search_path = public, extensions
as $$ select p_hash is not null and crypt(p_plain, p_hash) = p_hash $$;

-- ---------- Rule sets ----------
create table if not exists public.editions (
	id        smallint primary key,
	name      text     not null,
	enabled   boolean  not null default true
);

create table if not exists public.phases (
	edition     smallint not null references public.editions(id),
	phase_no    smallint not null check (phase_no between 1 and 10),
	-- e.g. [{"type":"set","count":3},{"type":"run","count":4}]
	conditions  jsonb    not null check (jsonb_typeof(conditions) = 'array'),
	primary key (edition, phase_no)
);

-- ---------- Players ----------
create table if not exists public.users (
	id             bigint generated by default as identity primary key,
	username       text        not null check (username ~ '^[A-Za-z0-9]{2,20}$'),
	password_hash  text        not null,
	role           text        not null default 'player' check (role in ('player','admin')),
	fullname       text        not null default '',
	photo          text        not null default 'na.png',
	email          text,
	phone          text,
	status         text        not null default 'active' check (status in ('active','suspended')),
	created_at     timestamptz not null default now(),
	last_login_at  timestamptz
);
create unique index if not exists users_username_lower_key on public.users (lower(username));

-- ---------- Games ----------
create table if not exists public.games (
	id             bigint generated by default as identity (start with 1000) primary key,
	host_id        bigint      not null references public.users(id),
	edition        smallint    not null default 1 references public.editions(id),
	pin            text        check (pin ~ '^[0-9]{4}$'),
	timer_sec      smallint    not null default 40 check (timer_sec in (0,20,30,40,50,60)),
	status         text        not null default 'lobby' check (status in ('lobby','playing','finished','abandoned')),
	round          smallint    not null default 0,
	version        bigint      not null default 0,
	state          jsonb,
	turn_user_id   bigint      references public.users(id),
	turn_deadline  timestamptz,
	next_game_id   bigint      references public.games(id),
	created_at     timestamptz not null default now(),
	updated_at     timestamptz not null default now(),
	finished_at    timestamptz
);
create index if not exists games_status_updated_idx on public.games (status, updated_at desc);
create index if not exists games_host_idx on public.games (host_id);

create table if not exists public.game_players (
	game_id     bigint      not null references public.games(id) on delete cascade,
	user_id     bigint      not null references public.users(id),
	seat        smallint    not null check (seat between 1 and 6),
	joined_at   timestamptz not null default now(),
	last_seen   timestamptz not null default now(),
	phase       smallint    not null default 1,
	score       integer     not null default 0,
	final_rank  smallint,
	primary key (game_id, user_id),
	unique (game_id, seat)
);
create index if not exists game_players_user_idx on public.game_players (user_id);

-- Leaderboard points: 1st place earns one point per player at the table, last place earns 1
create table if not exists public.game_points (
	id          bigint      generated by default as identity primary key,
	user_id     bigint      not null references public.users(id),
	game_id     bigint      not null references public.games(id) on delete cascade,
	points      smallint    not null check (points > 0),
	created_at  timestamptz not null default now(),
	unique (game_id, user_id)
);
create index if not exists game_points_created_idx on public.game_points (created_at);

-- ---------- Keep updated_at fresh ----------
create or replace function public.app_touch_updated_at()
returns trigger language plpgsql as $$
begin
	new.updated_at := now();
	return new;
end $$;

drop trigger if exists games_touch on public.games;
create trigger games_touch before update on public.games
	for each row execute function public.app_touch_updated_at();

-- ---------- Lock the tables away from browser clients ----------
alter table public.editions     enable row level security;
alter table public.phases       enable row level security;
alter table public.users        enable row level security;
alter table public.games        enable row level security;
alter table public.game_players enable row level security;
alter table public.game_points  enable row level security;

do $$
begin
	-- These roles exist only on Supabase; skip quietly on plain Postgres
	if exists (select 1 from pg_roles where rolname = 'anon') then
		revoke all on all tables in schema public from anon;
		revoke execute on function public.app_hash_password(text), public.app_check_password(text, text) from anon;
	end if;
	if exists (select 1 from pg_roles where rolname = 'authenticated') then
		revoke all on all tables in schema public from authenticated;
		revoke execute on function public.app_hash_password(text), public.app_check_password(text, text) from authenticated;
	end if;
end $$;
revoke execute on function public.app_hash_password(text), public.app_check_password(text, text) from public;

