-- 1. Admin password reset: the player must choose a new password at next sign-in
alter table public.users add column if not exists must_change_password boolean not null default false;

-- 2. When each player was last active anywhere in the app (friends list "online now / last seen")
alter table public.users add column if not exists last_seen_at timestamptz;

-- 3. Friends: one row per pair. requester asked, addressee accepts.
create table if not exists public.friendships (
	requester_id  bigint      not null references public.users(id) on delete cascade,
	addressee_id  bigint      not null references public.users(id) on delete cascade,
	status        text        not null default 'pending' check (status in ('pending', 'accepted')),
	created_at    timestamptz not null default now(),
	accepted_at   timestamptz,
	primary key (requester_id, addressee_id),
	check (requester_id <> addressee_id)
);
create index if not exists friendships_addressee_idx on public.friendships (addressee_id, status);
-- one friendship per pair, whichever way round it was asked
create unique index if not exists friendships_pair_idx on public.friendships (least(requester_id, addressee_id), greatest(requester_id, addressee_id));

-- 4. Invites to a table (shown on the friend's Play page; also sent as a phone alert)
create table if not exists public.game_invites (
	id          bigint      generated by default as identity primary key,
	game_id     bigint      not null references public.games(id) on delete cascade,
	from_id     bigint      not null references public.users(id) on delete cascade,
	to_id       bigint      not null references public.users(id) on delete cascade,
	status      text        not null default 'sent' check (status in ('sent', 'accepted', 'declined')),
	created_at  timestamptz not null default now(),
	unique (game_id, to_id)
);
create index if not exists game_invites_to_idx on public.game_invites (to_id, status, created_at desc);

-- 5. Phone alerts (Web Push): one row per phone / browser that allowed notifications
create table if not exists public.push_subscriptions (
	endpoint    text        primary key,
	user_id     bigint      not null references public.users(id) on delete cascade,
	p256dh      text        not null,
	auth        text        not null,
	created_at  timestamptz not null default now(),
	last_ok_at  timestamptz
);
create index if not exists push_subscriptions_user_idx on public.push_subscriptions (user_id);

-- Browser clients can't read these directly (only the app server can), like every other table
alter table public.friendships enable row level security;
alter table public.game_invites enable row level security;
alter table public.push_subscriptions enable row level security;
do $$
begin
	if exists (select 1 from pg_roles where rolname = 'anon') then
		revoke all on public.friendships, public.game_invites, public.push_subscriptions from anon;
	end if;
	if exists (select 1 from pg_roles where rolname = 'authenticated') then
		revoke all on public.friendships, public.game_invites, public.push_subscriptions from authenticated;
	end if;
end $$;
