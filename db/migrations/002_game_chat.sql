create table if not exists public.game_messages (
	id          bigint      generated by default as identity primary key,
	game_id     bigint      not null references public.games(id) on delete cascade,
	user_id     bigint      not null references public.users(id),
	body        text        not null check (char_length(body) between 1 and 200),
	created_at  timestamptz not null default now()
);
create index if not exists game_messages_game_idx on public.game_messages (game_id, id);

-- Browser clients can't read it directly (only the app server can), like every other table
alter table public.game_messages enable row level security;
do $$
begin
	if exists (select 1 from pg_roles where rolname = 'anon') then revoke all on public.game_messages from anon; end if;
	if exists (select 1 from pg_roles where rolname = 'authenticated') then revoke all on public.game_messages from authenticated; end if;
end $$;
